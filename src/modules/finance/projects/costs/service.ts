export async function costPercentagePreview(
  actor: Pick<Actor, "id">,
  input: unknown,
) {
  return withFinanceAccess(actor, async (tx) => {
    const q = costPreviewSchema.parse(input);
    await tx.$queryRaw`SELECT 1 FROM pg_advisory_xact_lock_shared(629815)`;
    const s = await readSource(tx, actor.id, q.sourceLineId);
    invariant(
      q.basisHash === s.basisHash,
      "FINANCE_COST_STALE_BASIS",
      errors.FINANCE_COST_STALE_BASIS,
      409,
    );
    invariant(
      s.item.net !== "0.00",
      "FINANCE_COST_SOURCE",
      errors.FINANCE_COST_SOURCE,
      422,
    );
    const ids = q.targets
      .map((t) => t.projectId)
      .filter((id): id is string => id !== null);
    invariant(
      (await tx.project.count({ where: { id: { in: ids } } })) === ids.length,
      "FINANCE_PROJECT_UNAVAILABLE",
      "Choose existing project dimensions.",
      422,
    );
    const amounts = splitCostPercentages(
      s.item.net,
      q.targets.map((t) => t.percentage),
    );
    return {
      sourceLineId: q.sourceLineId,
      basisHash: s.basisHash,
      sourceNet: s.item.net,
      targets: q.targets.map((t, i) => ({ ...t, amount: amounts[i] })),
    };
  });
}
