export async function forecasts(actor: Pick<Actor, "id">, input: unknown = {}) {
  return withFinanceAccess(actor, async (tx) => {
    const q = forecastQuerySchema.parse(input);
    await lock(tx);
    const where: Prisma.FinanceForecastWhereInput = {
      ...(q.kind !== "ALL" ? { kind: q.kind } : {}),
      ...(q.state !== "ALL" ? { state: q.state } : {}),
      ...(q.projectId
        ? { projectId: q.projectId === "SHARED" ? null : q.projectId }
        : {}),
      expectedDate: {
        gte: new Date(q.from + "T00:00:00Z"),
        lte: new Date(q.to + "T00:00:00Z"),
      },
      OR: [
        { number: { contains: q.q, mode: "insensitive" } },
        { description: { contains: q.q, mode: "insensitive" } },
        { project: { name: { contains: q.q, mode: "insensitive" } } },
        { party: { name: { contains: q.q, mode: "insensitive" } } },
      ],
    };
    const total = await tx.financeForecast.count({ where }),
      pages = Math.max(1, Math.ceil(total / 25)),
      page = Math.min(q.page, pages),
      items = await tx.financeForecast.findMany({
        where,
        include: {
          project: { select: { name: true } },
          party: { select: { name: true } },
        },
        orderBy: [
          { expectedDate: "asc" },
          { createdAt: "desc" },
          { id: "asc" },
        ],
        take: 25,
        skip: (page - 1) * 25,
      });
    return {
      items: items.map((i) => ({
        ...i,
        amount: i.amount.toFixed(2),
        expectedDate: day(i.expectedDate),
      })),
      total,
      pages,
      page,
      filters: q,
    };
  });
}
export async function planningOptions(
  actor: Pick<Actor, "id">,
  input: unknown = {},
) {
  return withFinanceAccess(actor, async (tx) => {
    const q = z
      .object({
        kind: z.enum(["BUDGET_ACCOUNT", "PARTY"]),
        q: z.string().trim().max(100).default(""),
        page: z.coerce.number().int().min(1).max(10000).default(1),
      })
      .strict()
      .parse(input);
    await lock(tx);
    if (q.kind === "BUDGET_ACCOUNT") {
      const where: Prisma.FinanceAccountWhereInput = {
          active: true,
          isPosting: true,
          isContra: false,
          controlType: "NONE",
          currency: "PKR",
          type: { in: ["DIRECT_COST", "OPERATING_EXPENSE", "OTHER_EXPENSE"] },
          OR: [
            { code: { contains: q.q, mode: "insensitive" } },
            { name: { contains: q.q, mode: "insensitive" } },
          ],
        },
        total = await tx.financeAccount.count({ where }),
        pages = Math.max(1, Math.ceil(total / 25)),
        page = Math.min(q.page, pages),
        items = await tx.financeAccount.findMany({
          where,
          select: { id: true, code: true, name: true },
          orderBy: [{ code: "asc" }, { id: "asc" }],
          take: 25,
          skip: (page - 1) * 25,
        });
      return { items, total, pages, page };
    }
    const where: Prisma.FinancePartyWhereInput = {
        active: true,
        OR: [
          { name: { contains: q.q, mode: "insensitive" } },
          { legalName: { contains: q.q, mode: "insensitive" } },
        ],
      },
      total = await tx.financeParty.count({ where }),
      pages = Math.max(1, Math.ceil(total / 25)),
      page = Math.min(q.page, pages),
      items = await tx.financeParty.findMany({
        where,
        select: { id: true, name: true, kind: true },
        orderBy: [{ name: "asc" }, { id: "asc" }],
        take: 25,
        skip: (page - 1) * 25,
      });
    return {
      items: items.map((i) => ({ id: i.id, code: i.kind, name: i.name })),
      total,
      pages,
      page,
    };
  });
}
